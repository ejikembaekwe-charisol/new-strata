// The token store, in the shapes other tools read.
//
// Lifted out of SharedProject so the public system page and a template's preview can offer
// the same three formats from the same code. They are pure functions of a token store, so
// a template — whose store is derived rather than saved — exports exactly what it would
// export once applied.

import { entranceKeyframesCss } from './motionKeyframes';
import { normalizeTypeKey } from './tokenTypes';

/** Walks a dotted token name into a nested object and sets the leaf. */
const setDeep = (root, name, leaf) => {
  const parts = String(name).split('.');
  let current = root;
  for (let i = 0; i < parts.length - 1; i++) {
    if (!current[parts[i]]) current[parts[i]] = {};
    current = current[parts[i]];
  }
  current[parts[parts.length - 1]] = leaf;
};

const eachToken = (tokensMap, fn) => {
  for (const cat in tokensMap || {}) {
    if (!Array.isArray(tokensMap[cat])) continue;
    tokensMap[cat].forEach(fn);
  }
};

/** `brand.color.primary` → `--brand-color-primary`. */
const cssVarName = (name) => '--' + String(name).replace(/\./g, '-');

/**
 * A token's value with any alias turned into a CSS reference.
 *
 * Derived tokens hold aliases like `{color.primary.main}`, which the app resolves at render
 * time — but written into a stylesheet as-is they are not CSS at all, and every consumer of
 * this function was emitting `--brand-color-primary: {color.primary.main};`. A reference to
 * a token in the same store becomes `var(--color-primary-main)`, which keeps the
 * relationship the token store describes instead of flattening it to a literal.
 *
 * A reference to something that is NOT in this store cannot be turned into anything true, so
 * it is left exactly as it is and the line says so. An invalid declaration the browser drops
 * is better than a value invented to fill the gap.
 */
const withAliasesResolved = (value, names) => {
  let dangling = null;
  const text = String(value).replace(/\{([^}]+)\}/g, (whole, ref) => {
    const target = ref.trim();
    if (names.has(target)) return 'var(' + cssVarName(target) + ')';
    dangling = target;
    return whole;
  });
  return { text, dangling };
};

export const cssVariablesFrom = (tokensMap) => {
  const names = new Set();
  eachToken(tokensMap, (t) => names.add(t.name));
  let css = '/* Auto-generated by Strata */\n:root {\n';
  eachToken(tokensMap, (t) => {
    const { text, dangling } = withAliasesResolved(t.value, names);
    css += '  ' + cssVarName(t.name) + ': ' + text + ';'
      + (dangling ? ' /* unresolved: no token named ' + dangling + ' */' : '') + '\n';
  });
  css += '}';
  // A motion.enter.* token is a keyframes name, so the keyframes have to travel with it
  // or the exported CSS names an animation the stylesheet does not define.
  return css + '\n\n' + entranceKeyframesCss();
};

export const tailwindThemeFrom = (tokensMap) => {
  const config = { theme: { extend: {} } };
  eachToken(tokensMap, (t) => setDeep(config.theme.extend, t.name, t.value));
  return JSON.stringify(config, null, 2);
};

export const dtcgJsonFrom = (tokensMap) => {
  const json = { $schema: 'https://tr.designtokens.org/format/' };
  eachToken(tokensMap, (t) => setDeep(json, t.name, { $value: t.value, $type: t.type }));
  return JSON.stringify(json, null, 2);
};

