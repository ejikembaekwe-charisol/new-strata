// ── The rest of the targets the Handoff grid offers ─────────────────────────
//
// The old Handoff tab advertised these six as sync URLs on a host that does not exist,
// with no generator behind any of them. They are generators now: pure functions of the
// same store the three above read, so what a card copies is what it downloads.

/** `brand.primary.500` → `brandPrimary500`, a valid identifier in every language here. */
const identFor = (name) => {
  const id = String(name)
    .replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ''))
    .replace(/^[^A-Za-z_]+/, '');
  return id || 'token';
};

/** Identifiers have to be unique within a file, and two token names can collide into one. */
const uniqueIdents = (tokensMap) => {
  const seen = new Map();
  const out = [];
  eachToken(tokensMap, (t) => {
    const base = identFor(t.name);
    const n = (seen.get(base) || 0) + 1;
    seen.set(base, n);
    out.push({ token: t, ident: n === 1 ? base : base + n });
  });
  return out;
};

const isColor = (t) => normalizeTypeKey(t.type) === 'color';

/**
 * A token's value as a number, where it has one.
 *
 * Returns null when the value is not a single measurement — a shadow, an easing curve, a
 * font stack — so the caller emits it as text rather than inventing a number for it. rem
 * and em resolve against a 16px root, which is CSS's own default and is written into the
 * generated comment so the assumption is visible in the file itself.
 */
const measure = (value) => {
  const m = /^(-?\d*\.?\d+)(px|rem|em|ms|s|%)?$/.exec(String(value).trim());
  if (!m) return null;
  const n = parseFloat(m[1]);
  const unit = m[2] || '';
  if (unit === '%') return null;
  if (unit === 'rem' || unit === 'em') return { n: n * 16, note: value + ' at a 16px root' };
  if (unit === 's') return { n: n * 1000, note: value + ' in milliseconds' };
  return { n, note: unit === 'ms' ? 'milliseconds' : '' };
};

/** #RGB / #RRGGBB / #RRGGBBAA → {r,g,b,a}; anything else — rgba(), a gradient — → null. */
const hexParts = (value) => {
  const m = /^#([0-9a-f]{3,8})$/i.exec(String(value).trim());
  if (!m) return null;
  let s = m[1];
  if (s.length === 3 || s.length === 4) s = s.split('').map(c => c + c).join('');
  if (s.length !== 6 && s.length !== 8) return null;
  return {
    r: parseInt(s.slice(0, 2), 16), g: parseInt(s.slice(2, 4), 16),
    b: parseInt(s.slice(4, 6), 16), a: s.length === 8 ? parseInt(s.slice(6, 8), 16) : 255,
  };
};

const JS_HEADER = '// Auto-generated by Strata. Edit your tokens, not this file.\n\n';

export const scssVariablesFrom = (tokensMap) => {
  let out = '// Auto-generated by Strata. Edit your tokens, not this file.\n\n';
  eachToken(tokensMap, (t) => {
    out += '$' + t.name.replace(/\./g, '-') + ': ' + t.value + ';\n';
  });
  return out;
};

const nestedValues = (tokensMap) => {
  const nested = {};
  eachToken(tokensMap, (t) => setDeep(nested, t.name, t.value));
  return nested;
};

/** An ES module: one named export per token, plus the nested `tokens` object. */
export const jsTokensFrom = (tokensMap) => {
  let out = JS_HEADER;
  uniqueIdents(tokensMap).forEach(({ token, ident }) => {
    out += 'export const ' + ident + ' = ' + JSON.stringify(token.value) + ';\n';
  });
  out += '\nexport const tokens = ' + JSON.stringify(nestedValues(tokensMap), null, 2) + ';\n';
  return out + '\nexport default tokens;\n';
};

/** The same, with `as const` so each value narrows to its literal rather than `string`. */
export const tsTokensFrom = (tokensMap) => {
  let out = JS_HEADER;
  uniqueIdents(tokensMap).forEach(({ token, ident }) => {
    out += 'export const ' + ident + ' = ' + JSON.stringify(token.value) + ' as const;\n';
  });
  out += '\nexport const tokens = ' + JSON.stringify(nestedValues(tokensMap), null, 2) + ' as const;\n';
  out += '\nexport type Tokens = typeof tokens;\n';
  return out + 'export default tokens;\n';
};

export const swiftTokensFrom = (tokensMap) => {
  let out = JS_HEADER
    + 'import SwiftUI\n\n'
    + 'extension Color {\n'
    + '    init(strataHex hex: String) {\n'
    + '        var s = hex.trimmingCharacters(in: CharacterSet.alphanumerics.inverted)\n'
    + '        if s.count == 3 { s = s.map { String(repeating: $0, count: 2) }.joined() }\n'
    + '        if s.count == 6 { s += "FF" }\n'
    + '        let v = UInt64(s, radix: 16) ?? 0xFFFFFFFF\n'
    + '        self.init(.sRGB,\n'
    + '                  red: Double((v >> 24) & 0xFF) / 255,\n'
    + '                  green: Double((v >> 16) & 0xFF) / 255,\n'
    + '                  blue: Double((v >> 8) & 0xFF) / 255,\n'
    + '                  opacity: Double(v & 0xFF) / 255)\n'
    + '    }\n'
    + '}\n\n'
    + 'public enum StrataTokens {\n';
  uniqueIdents(tokensMap).forEach(({ token, ident }) => {
    if (isColor(token) && hexParts(token.value)) {
      out += '    public static let ' + ident + ' = Color(strataHex: "' + token.value + '")\n';
      return;
    }
    const m = isColor(token) ? null : measure(token.value);
    if (m) {
      out += '    public static let ' + ident + ': CGFloat = ' + m.n
        + (m.note ? '  // ' + m.note : '') + '\n';
      return;
    }
    // A gradient, a shadow, an easing curve, a font stack: CSS text, and it stays text.
    out += '    public static let ' + ident + ' = ' + JSON.stringify(token.value) + '\n';
  });
  return out + '}\n';
};

export const dartTokensFrom = (tokensMap) => {
  let out = JS_HEADER
    + "import 'package:flutter/material.dart';\n\n"
    + 'class StrataTokens {\n'
    + '  StrataTokens._();\n\n';
  uniqueIdents(tokensMap).forEach(({ token, ident }) => {
    const c = isColor(token) ? hexParts(token.value) : null;
    if (c) {
      const argb = [c.a, c.r, c.g, c.b]
        .map(v => v.toString(16).toUpperCase().padStart(2, '0')).join('');
      out += '  static const Color ' + ident + ' = Color(0x' + argb + ');\n';
      return;
    }
    const m = isColor(token) ? null : measure(token.value);
    if (m) {
      out += '  static const double ' + ident + ' = ' + m.n + ';'
        + (m.note ? '  // ' + m.note : '') + '\n';
      return;
    }
    out += '  static const String ' + ident + ' = ' + JSON.stringify(token.value) + ';\n';
  });
  return out + '}\n';
};

/**
 * The project as one JSON file: every token with the fields the store actually holds, and
 * every component with the tokens mapped onto it. Strata's own shape rather than a
 * standard, which is why the version is stamped on it.
 */
export const strataJsonFrom = (tokensMap, meta = {}) => {
  const tokens = {};
  for (const cat in tokensMap || {}) {
    if (!Array.isArray(tokensMap[cat])) continue;
    tokens[cat] = tokensMap[cat].map(t => ({
      name: t.name, value: t.value, type: t.type,
      ...(t.tier || t.layer ? { tier: t.tier || t.layer } : {}),
      ...(t.description ? { description: t.description } : {}),
    }));
  }
  return JSON.stringify({
    format: 'strata.project',
    version: 1,
    project: {
      id: meta.id || null,
      name: meta.name || null,
      ...(meta.description ? { description: meta.description } : {}),
    },
    generatedAt: new Date().toISOString(),
    tokens,
    components: (meta.components || []).map(c => ({
      id: c.id,
      name: c.name,
      template: c.template,
      ...(c.description ? { description: c.description } : {}),
      ...(c.extends ? { extends: c.extends } : {}),
      tokens: c.tokens || {},
    })),
  }, null, 2);
};

